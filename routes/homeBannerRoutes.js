'use strict';
const express=require('express');
const router=express.Router();
const {protect,authorize}=require('../middleware/authMiddleware');
const {requirePermission}=require('../middleware/permissionMiddleware');
const c=require('../controllers/homeBannerController');
router.get('/',c.getActiveBanners);
router.get('/all',protect,authorize('admin'),requirePermission('content.manage'),c.getAllBanners);
router.post('/',protect,authorize('admin'),requirePermission('content.manage'),c.createBanner);
router.put('/reorder',protect,authorize('admin'),requirePermission('content.manage'),c.reorderBanners);
router.patch('/:id/toggle',protect,authorize('admin'),requirePermission('content.manage'),c.toggleBanner);
router.put('/:id',protect,authorize('admin'),requirePermission('content.manage'),c.updateBanner);
router.delete('/:id',protect,authorize('admin'),requirePermission('content.manage'),c.deleteBanner);
module.exports=router;
